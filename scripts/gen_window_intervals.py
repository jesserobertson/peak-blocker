"""Write tests/pacific_window_intervals.txt: each stretch of hours between 2024 and 2030
that falls inside the peak window (Mon-Fri 05:00-11:00 US Pacific), one "start end" pair
per line in Unix seconds with the end excluded.

The answers come from Python's zoneinfo, an implementation independent of the Rust
code under test. On Windows, `pip install tzdata` first so zoneinfo has the IANA data.
"""

import calendar
import datetime
import os
import zoneinfo

zone = zoneinfo.ZoneInfo("America/Los_Angeles")
first = calendar.timegm((2024, 1, 1, 0, 0, 0))
end = calendar.timegm((2031, 1, 1, 0, 0, 0))


def in_window(second: int) -> bool:
    local = datetime.datetime.fromtimestamp(second, datetime.timezone.utc).astimezone(zone)
    return local.isoweekday() <= 5 and 5 <= local.hour < 11


intervals = []
start = None
for hour_start in range(first, end, 3600):
    inside = in_window(hour_start)
    if inside and start is None:
        start = hour_start
    elif not inside and start is not None:
        intervals.append((start, hour_start))
        start = None
if start is not None:
    intervals.append((start, end))

path = os.path.join(os.path.dirname(__file__), "..", "tests", "pacific_window_intervals.txt")
os.makedirs(os.path.dirname(path), exist_ok=True)
with open(path, "w", newline="\n") as out:
    out.write("# Stretches of hours inside the peak window, 2024-2030, from Python zoneinfo.\n")
    out.write("# Generated by scripts/gen_window_intervals.py; the end of each is excluded.\n")
    for a, b in intervals:
        out.write(f"{a} {b}\n")
print(len(intervals), "windows written to", os.path.normpath(path))
